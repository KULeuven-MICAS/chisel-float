package fp_unit

import java.nio.charset.StandardCharsets
import java.nio.file.Files

import chiseltest._
import chiseltest.simulator.VcsBackendAnnotation
import chiseltest.simulator.VerilatorBackendAnnotation
import chiseltest.simulator.VerilatorFlags
import firrtl2.annotations.Annotation

/** Test settings from environment variables or JVM properties (e.g. `-Dfp.sim=vcs`); see the README. */
object FpTestConfig {

  private def setting(name: String): Option[String] =
    sys.props
      .get(name.toLowerCase.replace('_', '.'))
      .orElse(sys.env.get(name))
      .map(_.trim)
      .filter(_.nonEmpty)

  val backend:  String  = setting("FP_SIM").getOrElse("verilator").toLowerCase
  val level:    String  = setting("FP_TEST_LEVEL").getOrElse("default").toLowerCase
  val seed:     Long    = setting("FP_TEST_SEED").map(_.toLong).getOrElse(2025L)
  val writeVcd: Boolean = setting("FP_VCD").exists(v => v == "1" || v.equalsIgnoreCase("true"))

  require(Set("verilator", "vcs").contains(backend), s"FP_SIM must be 'verilator' or 'vcs', got '$backend'")
  require(
    Set("quick", "default", "extended").contains(level),
    s"FP_TEST_LEVEL must be 'quick', 'default' or 'extended', got '$level'"
  )

  def isQuick:    Boolean = level == "quick"
  def isExtended: Boolean = level == "extended"

  /** Scales a default random-vector count with the test level. */
  def scaled(n: Int): Int =
    level match {
      case "quick"    => math.max(n / 10, 1)
      case "extended" => n * 10
      case _          => n
    }

  // Verilator 5 gives every model a thread pool and chiseltest never unloads models, so long runs hit `ulimit -u`.
  // This file, compiled into every model, makes the default context single-threaded.
  private lazy val singleThreadedContext: String = {
    val dir  = Files.createTempDirectory("chisel-float-verilator")
    val file = dir.resolve("single_threaded_context.cpp")
    val code =
      """// Generated by chisel-float's FpTestConfig.scala: keep Verilator's default context single-threaded.
        |#include "verilated.h"
        |#if defined(VERILATOR_VERSION_INTEGER) && VERILATOR_VERSION_INTEGER >= 5000000
        |namespace {
        |struct SingleThreadedDefaultContext {
        |  SingleThreadedDefaultContext() { Verilated::defaultContextp()->threads(1); }
        |};
        |const SingleThreadedDefaultContext singleThreadedDefaultContext;
        |}  // namespace
        |#endif
        |""".stripMargin
    Files.write(file, code.getBytes(StandardCharsets.UTF_8))
    dir.toFile.deleteOnExit() // deleted in reverse order: the file first, then its directory
    file.toFile.deleteOnExit()
    file.toAbsolutePath.toString
  }

  // Keeps each model in one C++ file: GCC rejects the precompiled header of split models, because chiseltest
  // force-includes the model header first. `--output-split 0` still splits the constant pool.
  private val noOutputSplit = "100000000"

  def annotations: Seq[Annotation] = {
    val sim =
      if (backend == "vcs") Seq(VcsBackendAnnotation)
      else Seq(VerilatorBackendAnnotation, VerilatorFlags(Seq("--output-split", noOutputSplit, singleThreadedContext)))
    if (writeVcd) sim :+ WriteVcdAnnotation else sim
  }
}
